/** `match.proposal.create` -> `match__proposal__create`: message keys allow no dots (i18n-core §1.3). */
export type AuditActionKey<S extends string = AuditAction> = S extends `${infer H}.${infer T}`
  ? `${H}__${AuditActionKey<T>}`
  : S;

