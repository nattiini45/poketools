import { NextRequest, NextResponse } from 'next/server';
import { requireAdmin } from '@/lib/auth/helpers';
import { safeErrorResponse } from '@/lib/api/error-response';
import {
  getReplayEventsByPool,
  createReplayEvent,
} from '@/lib/supabase/queries/draft-replay-events';
import { supabase } from '@/lib/supabase/client';
import type { ApiResult } from '@/types/api';
import type { DraftReplayEvent, DraftReplayEventInsert } from '@/types/broadcast';
import { draftReplayEventSchema, formatZodErrors } from '@/lib/validation';

interface RouteContext {
  params: Promise<{ id: string }>;
}

/** A replay event plus the drafted line id of its pick (EPB pools; null otherwise). */
type ReplayEventWithLine = DraftReplayEvent & { line_id: string | null };

/**
 * pick id → line id of a pool's picks. A narrow select (`id, line_id`): no other
 * pick column and no player join is read, so nothing private can leak.
 */
async function lineIdsByPick(poolId: string): Promise<Map<string, string>> {
  const { data, error } = await supabase.from('draft_picks').select('id, line_id').eq('draft_pool_id', poolId);
  if (error) throw error;
  const lineByPick = new Map<string, string>();
  for (const pick of data ?? []) {
    if (pick.line_id) lineByPick.set(pick.id, pick.line_id);
  }
  return lineByPick;
}

/**
 * GET /api/drafts/[id]/replay-events — public, for replay playback. Each event carries the `line_id` of its
 * pick (EPB), so the overlay can label the line instead of a bare species.
 */
// Public: no auth required
export async function GET(_request: NextRequest, context: RouteContext) {
  try {
    const { id } = await context.params;
    const [events, lineByPick] = await Promise.all([getReplayEventsByPool(id), lineIdsByPick(id)]);
    const data: ReplayEventWithLine[] = events.map((event) => ({
      ...event,
      line_id: event.pick_id ? (lineByPick.get(event.pick_id) ?? null) : null,
    }));

    return NextResponse.json<ApiResult<ReplayEventWithLine[]>>({
      success: true,
      data,
    });
  } catch (err) {
    return safeErrorResponse(err, 'Failed to fetch draft replay events');
  }
}

/** POST /api/drafts/[id]/replay-events — admin only, add commentary/pause events */
export async function POST(request: NextRequest, context: RouteContext) {
  try {
    await requireAdmin();
    const { id } = await context.params;
    const rawBody = await request.json();
    const zodResult = draftReplayEventSchema.safeParse(rawBody);
    if (!zodResult.success) {
      const issues = formatZodErrors(zodResult.error);
      return NextResponse.json<ApiResult<never>>(
        { success: false, error: issues, code: 'validation_failed', params: { issues } },
        { status: 400 }
      );
    }
    const body = zodResult.data;

    // Only allow adding non-pick events via this endpoint
    // Pick events are auto-generated by the draft pick endpoint
    if (body.event_type === 'pick') {
      return NextResponse.json<ApiResult<never>>(
        {
          success: false,
          error: 'Pick events are auto-generated. Use POST /api/drafts/[id]/picks instead.',
          code: 'REPLAY_PICK_EVENTS_AUTO',
        },
        { status: 400 }
      );
    }

    const event = await createReplayEvent({
      ...(rawBody as Omit<DraftReplayEventInsert, 'draft_pool_id'>),
      draft_pool_id: id,
    });

    return NextResponse.json<ApiResult<DraftReplayEvent>>({
      success: true,
      data: event,
    });
  } catch (err) {
    return safeErrorResponse(err, 'Failed to create draft replay event');
  }
}
