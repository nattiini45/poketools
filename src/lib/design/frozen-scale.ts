/** The root font size frozen surfaces were built against. */
export const FROZEN_ROOT_PX = 18;

function customProperties(css: string): Map<string, string> {
  const props = new Map<string, string>();
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/@theme[^{]*\breference\b[^{]*\{[^}]*\}/g, '');
  for (const match of text.matchAll(/(--[\w-]+)\s*:\s*([^;{}]+);/g)) props.set(match[1], match[2].trim().replace(/\s+/g, ' '));
  return props;
}

function remToPx(value: string): string {
  return value.replace(/(-?\d*\.?\d+)rem\b/g, (_, n: string) => `${Number((Number(n) * FROZEN_ROOT_PX).toFixed(4))}px`);
}

/**
 * Every custom property the stylesheets declare in rem, resolved at the frozen 18 px root. Tailwind 4 utilities read
 * these variables where they are used, so re-declaring them as px on a [data-frozen] root keeps its subtree at the
 * sizes it had before the root went to 16 px. Later stylesheets override earlier ones, as in the cascade; a name
 * declared with two different rem values is an error, because one pin could not hold both.
 */
export function frozenScaleDeclarations(...stylesheets: string[]): Array<[string, string]> {
  const final = new Map<string, string>();
  const remValues = new Map<string, Set<string>>();
  for (const css of stylesheets) {
    for (const [name, value] of customProperties(css)) {
      final.set(name, value);
      if (/\drem\b/.test(value)) remValues.set(name, (remValues.get(name) ?? new Set()).add(value));
    }
  }
  const out: Array<[string, string]> = [];
  for (const [name, value] of final) {
    if (!/\drem\b/.test(value)) continue;
    if (remValues.get(name)!.size > 1) throw new Error(`${name} is declared with more than one rem value`);
    out.push([name, remToPx(value)]);
  }
  return out.sort(([a], [b]) => a.localeCompare(b));
}

export function frozenScaleCss(...stylesheets: string[]): string {
  const body = frozenScaleDeclarations(...stylesheets).map(([name, value]) => `  ${name}: ${value};`).join('\n');
  return `/* ─── Frozen-surface scale (redesign F3) ───
 Generated by \`npx --no-install tsx scripts/design/frozen-scale.mts\`; do not edit by hand.
 The root is 16 px since F3. Every [data-frozen] root re-declares each rem-valued token of the Tailwind theme and
 globals.css at the 18 px root it was built against, and its outermost root the font size it inherits from <body>, so frozen subtrees
 render exactly as before. frozen-scale.test.ts fails when this file is stale. */
[data-frozen] {
${body}
}
:where([data-frozen]:not([data-frozen] *)) {
  font-size: ${FROZEN_ROOT_PX}px;
}
`;
}
