#!/usr/bin/env node
/**
 * Writes src/lib/broadcast/wiki-overlay-ids.generated.ts: every move, item, ability and species id that the broadcast
 * wiki overlays and the public wiki pages resolve (a NatDex walk of generations 1-9, the same rule as getMoveNatDex /
 * getItemNatDex / getAbilityNatDex / getSpeciesNatDex in src/lib/pkmn/dex.ts), including the alias spellings @pkmn
 * accepts.
 *
 * The proxy answers 404 for an unknown overlay or wiki name before the page streams, and it must not bundle @pkmn/dex (2 MB+),
 * so it reads this compact list instead. src/lib/broadcast/__tests__/wiki-overlay-ids.test.ts fails when the file is
 * out of date after a @pkmn upgrade; run `node scripts/generate-wiki-overlay-ids.mjs` to refresh it.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Generations } from '@pkmn/data';
import { Dex, toID } from '@pkmn/dex';

const MIN_GEN = 1;
const MAX_GEN = 9;
const OUTPUT = fileURLToPath(new URL('../src/lib/broadcast/wiki-overlay-ids.generated.ts', import.meta.url));

const KINDS = /** @type {const} */ ({ moves: 'MOVE_IDS', items: 'ITEM_IDS', abilities: 'ABILITY_IDS', species: 'SPECIES_IDS' });

const SPECIES_PREFIXES = ['mega', 'primal', 'gigantamax'];
const FORM_SUFFIX = /(mega[xyz]?|primal|gmax)$/;

/** An alias key that points at a non-species makes @pkmn's species lookup throw; the page would 500 on it, so it never resolves. */
function lookup(table, id) {
  try {
    return table.get(id);
  } catch {
    return undefined;
  }
}

export function collectWikiOverlayIds() {
  const gens = new Generations(Dex);
  const candidates = { moves: new Set(), items: new Set(), abilities: new Set(), species: new Set() };
  const aliasKeys = new Set();
  for (let g = MIN_GEN; g <= MAX_GEN; g++) {
    const gen = gens.get(g);
    for (const kind of Object.keys(candidates)) {
      for (const entity of gen[kind]) candidates[kind].add(entity.id);
    }
    for (const key of Object.keys(Dex.forGen(g).data.Aliases)) aliasKeys.add(key);
  }
  // @pkmn reads "Mega-<name>", "Primal-<name>" and "Gigantamax-<name>" as the form's id. The gate has no prefix rule of
  // its own: a prefixed spelling is a valid species name only when it lands in this list, so every one is tried here
  // (the base forms of the Mega, Primal and Gigantamax ids included) and kept only when the NatDex walk resolves it.
  const speciesIds = [...candidates.species];
  const prefixed = new Set();
  for (const prefix of SPECIES_PREFIXES) {
    for (const id of [...speciesIds, ...aliasKeys]) {
      prefixed.add(prefix + id);
      prefixed.add(prefix + id.replace(FORM_SUFFIX, ''));
    }
  }

  /** @type {Record<'moves' | 'items' | 'abilities' | 'species', string[]>} */
  const ids = { moves: [], items: [], abilities: [], species: [] };
  for (const kind of Object.keys(candidates)) {
    const resolved = new Set();
    const tried = kind === 'species' ? [...candidates[kind], ...aliasKeys, ...prefixed] : [...candidates[kind], ...aliasKeys];
    for (const id of tried) {
      for (let g = MIN_GEN; g <= MAX_GEN; g++) {
        const entity = lookup(gens.get(g)[kind], id);
        if (entity && entity.exists && !(kind === 'species' && (entity.battleOnly || entity.isNonstandard))) {
          resolved.add(toID(id));
          break;
        }
      }
    }
    ids[kind] = [...resolved].sort();
  }
  return ids;
}

/**
 * The type spellings "Hidden Power <Type>" resolves for: @pkmn answers "hiddenpowerfire" (and "hiddenpowerfire60") with
 * the Hidden Power move, but only for a type it knows, so the proxy cannot treat every "hiddenpower..." id as valid.
 */
export function collectHiddenPowerTypes() {
  const gens = new Generations(Dex);
  const types = new Set();
  for (let g = MIN_GEN; g <= MAX_GEN; g++) {
    const gen = gens.get(g);
    for (const type of gen.types) {
      const id = toID(type.name);
      const move = id && gen.moves.get('hiddenpower' + id);
      if (move && move.exists) types.add(id);
    }
  }
  return [...types].sort();
}

function render(ids, hiddenPowerTypes) {
  const parts = [
    '// Generated by scripts/generate-wiki-overlay-ids.mjs. Do not edit by hand.',
    '',
  ];
  for (const [kind, name] of Object.entries(KINDS)) {
    parts.push(`export const ${name} = ${JSON.stringify(ids[kind].join('|'))};`, '');
  }
  parts.push(`export const HIDDEN_POWER_TYPES = ${JSON.stringify(hiddenPowerTypes.join('|'))};`, '');
  return parts.join('\n').trimEnd() + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, render(collectWikiOverlayIds(), collectHiddenPowerTypes()));
  console.log(`wrote ${OUTPUT}`);
}
