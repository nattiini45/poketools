/**
 * Writes PRIVATE workbook data; the committed fixture
 * (`src/lib/draft/__tests__/fixtures/example-list.json`) comes from
 * scripts/draft/make-example-list-fixtures.ts — do not commit this output.
 *
 * Dumps a league's point-buy workbook in the shape of the EPB list test fixture,
 * through the importer's own parser (the active format pack's workbook layout,
 * `@/lib/format-pack`). No database access. Useful for checking a workbook locally
 * against the synthetic fixture's structure.
 *
 * Usage:
 *   npx tsx --tsconfig tsconfig.json scripts/draft/dump-list-fixture.ts \
 *     --xlsx <path to the point-buy workbook> \
 *     --out <path outside the committed fixtures>
 *
 * The workbook is not in the repository: the league organiser supplies it privately.
 */

import { existsSync, readFileSync, writeFileSync } from 'fs';
import { basename, resolve } from 'path';
import { parsePointBuyXlsxBuffer, pointBuyEntriesToRows } from '@/lib/import/point-buy-xlsx';
import { guardPrivateOutput } from '../lib/private-output-guard.mjs';

function argValue(args: string[], name: string): string | null {
  const eq = args.find((a) => a.startsWith(`--${name}=`));
  if (eq) return eq.slice(name.length + 3);
  const idx = args.indexOf(`--${name}`);
  if (idx !== -1 && idx + 1 < args.length && !args[idx + 1].startsWith('--')) return args[idx + 1];
  return null;
}

function trimEmptyTail(rows: string[][]): string[][] {
  let end = rows.length;
  while (end > 0 && !rows[end - 1].some(Boolean)) end--;
  return rows.slice(0, end).map((row) => {
    let last = row.length;
    while (last > 0 && !row[last - 1]) last--;
    return row.slice(0, last);
  });
}

function main() {
  const args = process.argv.slice(2);
  const xlsxPath = argValue(args, 'xlsx');
  if (!xlsxPath) {
    console.error('Pass the workbook path with --xlsx <path>. The workbook is not in the repository.');
    process.exit(2);
  }
  const outPath = argValue(args, 'out');
  if (!outPath) {
    console.error('Pass --out <path>. This writes PRIVATE workbook data; it must not overwrite the committed synthetic fixture.');
    process.exit(1);
  }
  // Outside the repository or git-ignored only: never a committed fixture or any other tracked file.
  const outFile = guardPrivateOutput(outPath);

  if (!existsSync(resolve(process.cwd(), xlsxPath))) {
    console.error(
      `Workbook not found: ${xlsxPath}. League workbooks are not in the repository; the league organiser supplies them privately. Pass its path with --xlsx <path>.`
    );
    process.exit(2);
  }
  const workbook = parsePointBuyXlsxBuffer(readFileSync(resolve(process.cwd(), xlsxPath)));
  // The rows exactly as the importer writes them, minus the version id.
  const entries = pointBuyEntriesToRows('fixture', workbook.entries).map((row) => {
    const { list_version_id: _versionId, ...rest } = row;
    void _versionId;
    return rest;
  });

  const fixture = {
    $comment:
      'Generated by scripts/draft/dump-list-fixture.ts from a point-buy workbook (importer rows, sheet values; league overrides are NOT applied). Do not edit by hand.',
    source: basename(xlsxPath),
    overview: workbook.overview,
    // Row positions are kept (the report cites sheet row numbers); only the empty tail is dropped.
    rules_sheet_rows: trimEmptyTail(workbook.rulesSheetRows),
    entries,
  };
  writeFileSync(outFile,`${JSON.stringify(fixture, null, 2)}\n`, 'utf-8');
  console.log(`Wrote ${entries.length} entries to ${outPath}`);
}

main();
