#!/usr/bin/env node
// scripts/pkmn-i18n/generate.mjs: writes src/lib/pkmn/i18n/data/* from the pinned PokeAPI CSVs, the app's @pkmn
// universe and the reviewed overrides (design pkmn-l10n.md §1). Run from anywhere; paths resolve from the repo root.
//
//   node scripts/pkmn-i18n/fetch-csv.mjs            # once: fills the gitignored .cache/
//   node scripts/pkmn-i18n/generate.mjs             # regenerate the committed data files
//   node scripts/pkmn-i18n/generate.mjs --check     # regenerate in memory; exit 1 if any committed file differs,
//                                                   is missing, or is a stray file the generator does not write
//
// Options: --csv-dir <dir> (default scripts/pkmn-i18n/.cache/csv), --out-dir <dir> (default src/lib/pkmn/i18n/data),
// --overrides-dir <dir> (default scripts/pkmn-i18n/overrides).
// Exit 1 also when a CSV hash differs from source.json, or when a NatDex id has no German name and no allowlist row.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { buildAll, parseCsv, serialize } from './build.mjs';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, '..', '..');

const KINDS = ['species', 'moves', 'items', 'abilities', 'natures', 'types'];

const DATA_README = `# Generated German Pokémon data

Generated by \`scripts/pkmn-i18n/generate.mjs\` from PokeAPI CSVs (BSD-3-Clause, see \`../NOTICE.md\`) and the app's
\`@pkmn/dex\` universe. **Do not edit these files.** Edit \`scripts/pkmn-i18n/overrides/*\` and regenerate:

\`\`\`bash
node scripts/pkmn-i18n/fetch-csv.mjs
node scripts/pkmn-i18n/generate.mjs
node scripts/pkmn-i18n/generate.mjs --check
\`\`\`

Keys are @pkmn ids (\`toID\` from \`src/lib/pkmn/i18n/id.ts\`). Name maps (\`species|moves|items|abilities|misc.de.json\`)
are client-importable, one kind per module; the \`*.desc.de.json\` description maps are server-only.
Pinned source commit, CSV hashes and entry counts: \`_meta.json\`.
`;

function parseArgs(argv) {
  const out = {
    csvDir: join(SCRIPT_DIR, '.cache', 'csv'),
    outDir: join(REPO_ROOT, 'src', 'lib', 'pkmn', 'i18n', 'data'),
    overridesDir: join(SCRIPT_DIR, 'overrides'),
    check: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') out.check = true;
    else if (a === '--csv-dir') out.csvDir = resolve(argv[++i]);
    else if (a === '--out-dir') out.outDir = resolve(argv[++i]);
    else if (a === '--overrides-dir') out.overridesDir = resolve(argv[++i]);
    else throw new Error(`unknown argument: ${a}`);
  }
  return out;
}

function readOverride(dir, file) {
  const o = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  delete o._comment;
  return o;
}

/** The app's universe: the same gens 1–9 walk as src/lib/pkmn/dex.ts (new Generations(Dex)), plus cosmetic and Gmax formes. */
function buildUniverses() {
  const req = createRequire(join(REPO_ROOT, 'package.json'));
  const { Dex } = req('@pkmn/dex');
  const { Generations } = req('@pkmn/data');
  const gens = new Generations(Dex);
  const pkmnDexVersion = JSON.parse(readFileSync(req.resolve('@pkmn/dex/package.json'), 'utf8')).version;
  const sortMap = (m) => new Map([...m].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  const entry = (e) => ({ name: e.name, num: e.num, forme: e.forme, gender: e.gender });
  const natdex = {};
  for (const kind of KINDS) {
    const m = new Map();
    for (let g = 1; g <= 9; g++) for (const e of gens.get(g)[kind]) m.set(e.id, kind === 'species' ? entry(e) : { name: e.name });
    natdex[kind] = sortMap(m);
  }
  const species = new Map(natdex.species);
  for (const s of natdex.species.values()) {
    for (const cosmetic of Dex.species.get(s.name).cosmeticFormes ?? []) {
      const c = Dex.species.get(cosmetic);
      if (c.exists && !species.has(c.id)) species.set(c.id, entry(c));
    }
  }
  for (const s of Dex.species.all()) if (s.forme === 'Gmax' && !species.has(s.id)) species.set(s.id, entry(s));
  return { universes: { ...natdex, species: sortMap(species) }, natdex, pkmnDexVersion };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const source = JSON.parse(readFileSync(join(SCRIPT_DIR, 'source.json'), 'utf8'));

  const tables = {};
  const hashErrors = [];
  for (const name of Object.keys(source.csvSha256)) {
    const file = join(args.csvDir, `${name}.csv`);
    if (!existsSync(file)) {
      hashErrors.push(`${name}.csv missing in ${args.csvDir} (run node scripts/pkmn-i18n/fetch-csv.mjs)`);
      continue;
    }
    const buf = readFileSync(file);
    const got = createHash('sha256').update(buf).digest('hex');
    if (got !== source.csvSha256[name]) hashErrors.push(`${name}.csv sha256 ${got} != pinned ${source.csvSha256[name]}`);
    tables[name] = parseCsv(buf.toString('utf8'));
  }
  if (hashErrors.length) {
    for (const e of hashErrors) console.error(e);
    process.exit(1);
  }

  const { universes, natdex, pkmnDexVersion } = buildUniverses();
  const overrides = {
    forms: readOverride(args.overridesDir, 'forms.de.json'),
    abilities: readOverride(args.overridesDir, 'abilities.de.json'),
    items: readOverride(args.overridesDir, 'items.de.json'),
    misc: readOverride(args.overridesDir, 'misc.de.json'),
    desc: readOverride(args.overridesDir, 'desc.de.json'),
  };
  const allowlist = readOverride(args.overridesDir, 'fallback-allowlist.json');
  const { files, report } = buildAll({ tables, universes, overrides });

  const counts = {};
  const sizes = {};
  for (const [file, data] of Object.entries(files)) {
    const text = serialize(data);
    counts[file] = Object.keys(data).length;
    sizes[file] = { raw: Buffer.byteLength(text), gzip: gzipSync(text, { level: 9 }).length };
  }
  const meta = {
    source: source.repo,
    commit: source.commit,
    license: source.license,
    csvSha256: source.csvSha256,
    pkmnDex: pkmnDexVersion,
    counts,
    generator: 'scripts/pkmn-i18n/generate.mjs',
  };
  const outputs = {
    ...Object.fromEntries(Object.entries(files).map(([f, d]) => [f, serialize(d)])),
    '_meta.json': serialize(meta),
    'README.md': DATA_README,
  };

  // NatDex ids (not the cosmetic/Gmax extras, which fall back to their base name at runtime) need a name or a row.
  const unexplained = [];
  for (const kind of KINDS) {
    const allowed = allowlist[kind] ?? {};
    for (const id of report.missing[kind]) if (natdex[kind].has(id) && !Object.hasOwn(allowed, id)) unexplained.push(`${kind}:${id}`);
  }
  const unused = Object.entries(report.unusedOverrides).flatMap(([k, ids]) => ids.map((id) => `${k}:${id}`));

  console.log(JSON.stringify({ sizes, report }, null, 1));

  let failed = false;
  if (unexplained.length) {
    console.error(`No German name and no fallback-allowlist row: ${unexplained.join(', ')}`);
    failed = true;
  }
  if (unused.length) {
    console.error(`Override rows that match no universe id: ${unused.join(', ')}`);
    failed = true;
  }

  if (args.check) {
    const stale = [];
    for (const [file, text] of Object.entries(outputs)) {
      const path = join(args.outDir, file);
      if (!existsSync(path) || readFileSync(path, 'utf8') !== text) stale.push(relative(REPO_ROOT, path));
    }
    // A file the generator does not write (stray, or left behind by a rename) is drift too.
    const stray = existsSync(args.outDir)
      ? readdirSync(args.outDir, { withFileTypes: true })
          .filter((e) => !Object.hasOwn(outputs, e.name))
          .map((e) => relative(REPO_ROOT, join(args.outDir, e.name)))
      : [];
    if (stale.length) {
      console.error(`--check: out of date: ${stale.join(', ')}. Run node scripts/pkmn-i18n/generate.mjs`);
      failed = true;
    }
    if (stray.length) {
      console.error(`--check: not written by the generator (stray or renamed): ${stray.join(', ')}. Delete them or update the generator.`);
      failed = true;
    }
    if (!stale.length && !stray.length) console.log(`--check: ${Object.keys(outputs).length} files up to date`);
  } else if (!failed) {
    mkdirSync(args.outDir, { recursive: true });
    for (const [file, text] of Object.entries(outputs)) writeFileSync(join(args.outDir, file), text);
    console.log(`wrote ${Object.keys(outputs).length} files to ${relative(REPO_ROOT, args.outDir)}`);
  }
  if (failed) process.exit(1);
}

main();
